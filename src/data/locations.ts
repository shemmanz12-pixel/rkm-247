export function formatLocationNameFromSlug(slug: string): string {
  const match = locations.find((l) => l.slug === slug);
  if (match) return match.name;

  return slug
    .split("-")
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ");
}